// Coordination metadata — turn a gap list into a plan someone can actually execute.
//
// The assessment already answers "what is broken" and "why it matters" (shared/requirements.ts
// REQUIREMENT_GUIDANCE) and "what to do about it" (`fix`). What it did NOT answer is the set of
// questions that actually decide whether a dealership closes the gap:
//
//    Who owns this?  How much work is it?  What artifact proves it is done?
//    What is the exposure if it slips?  What can realistically be finished in 30 days?
//
// Compliance programs usually fail as a COORDINATION problem, not a knowledge problem: the GM
// says it belongs to IT, IT says it is a policy question, and nothing moves. This module encodes
// the routing so the product ships a plan rather than a finding list.
//
// Pure, dependency-free, and authored (mirrors REQUIREMENT_GUIDANCE): keyed by requirement code,
// consumed by shared/task-derivation.ts, shared/pdf-generator.ts, and the Dashboard / Tasks /
// Summary surfaces. Never generated by an LLM, and never used to decide pass/fail — status stays
// deterministic in shared/derivation.ts.
//
// TWO DELIBERATE CALLS, both confirmed against dealership operating experience (2026-07-29):
//
//  1. NO VENDOR-PARTICIPATION FIELD. An earlier draft flagged which outside party (DMS vendor,
//     MSP, counsel) had to be involved. It was removed: in practice a named outside dependency
//     reads as a ready-made reason to defer, and the dealership owns the obligation under the
//     Rule regardless of who it delegates the work to. Every item here is internally owned.
//
//  2. CONSEQUENCES ARE FRAMED AS REGULATORY EXPOSURE, not operational inconvenience. Enforcement
//     is what actually moves a dealer principal to spend. But this is scoped strictly to the
//     `consequence` lines — the Dashboard and landing-page copy stay calibrated and non-alarmist
//     on purpose. Each line stays grounded in the Rule's own text (what §314.4 makes mandatory,
//     what an examiner requests first). No invented penalty figures, no speculative enforcement
//     claims — the same evidentiary bar as every other authored string in this codebase.

/** Task priority enum, matching drizzle/schema.ts taskPriorityEnum.
 *  Declared HERE rather than in task-derivation.ts so this module has no imports at all:
 *  task-derivation imports coordination, and a back-import would make the pair cyclic. The
 *  Deno edge runtime resolves these modules live rather than bundling them, so the dependency
 *  is kept strictly one-directional. task-derivation re-exports this for its existing callers. */
export type TaskPriority = 'low' | 'medium' | 'high' | 'critical';

/** Who inside the dealership is accountable for closing the gap. */
export type OwnerRole =
  | 'ownership'
  | 'qualified_individual'
  | 'gm_controller'
  | 'it_msp'
  | 'hr_training';

/** Rough size of the work — drives sequencing, not scoring. */
export type Effort = 'quick' | 'moderate' | 'project';

/** Planning horizon in days: what to do now / next / after that. */
export type Horizon = 30 | 60 | 90;

export interface Coordination {
  /** The accountable internal owner. One role — shared ownership is how gaps stall. */
  owner: OwnerRole;
  effort: Effort;
  /** The artifact that proves this is closed — what to upload to Evidence. */
  proof: string;
  /** The regulatory exposure created by leaving this open (see note 2 in the header). */
  consequence: string;
}

