/** Coordination for a requirement code, falling back honestly rather than fabricating. */
export function getCoordination(code: string): Coordination {
  return COORDINATION_BY_CODE[code] ?? COORDINATION_FALLBACK;
}

/**
 * Planning horizon for a piece of remediation — "what can be done in the next 30 days".
 *
 * Deterministic matrix over (priority, effort). EFFORT DOMINATES, deliberately: 23 of the 45
 * requirements carry the `critical` scoring weight, so sequencing on urgency alone puts ~31
 * items in the first 30 days, which is not a plan — it is the same undifferentiated gap list
 * with a deadline on it. Promising more than a month can hold is exactly how a remediation
 * roadmap loses credibility on first review.
 *
 * So the 30-day bucket holds only work that is BOTH urgent and genuinely short (under a day),
 * which is also the right behavioural bias: a store that closes fifteen small items in month
 * one keeps going. Nothing critical is ever parked past 60 days.
 */
export function horizonFor(priority: TaskPriority, effort: Effort): Horizon {
  if (priority === 'critical') return effort === 'quick' ? 30 : 60;
  if (priority === 'high') return effort === 'quick' ? 30 : 90;
  return effort === 'quick' ? 60 : 90;
}

